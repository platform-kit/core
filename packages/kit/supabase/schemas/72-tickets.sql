-- A TICKET RAISED BY A FORM.
--
-- A desk that spends its first three replies asking "what version, what did you try, how urgent is
-- it" is a desk doing work a form could have done. So a form may BE the way a ticket is raised:
-- its response becomes the ticket's, the answers stay where every other form answer lives, and the
-- desk reads and filters them through the response without this table ever learning what a field is.
--
-- It is called by the `form` function with the service role once an answer is finished — never by a
-- client, which is why it takes the contact and the response rather than working them out from
-- auth.uid().
CREATE OR REPLACE FUNCTION "public"."support_ticket_from_form"(
      "p_title" "text", "p_response" "uuid", "p_contact" "uuid" DEFAULT NULL::"uuid",
      "p_body" "text" DEFAULT NULL::"text", "p_priority" "text" DEFAULT 'normal'::"text",
      "p_category" "text" DEFAULT NULL::"text") RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
declare t public.support_tickets;
begin
  if coalesce(trim(p_title), '') = '' then return jsonb_build_object('error', 'title'); end if;
  /* one answer, one ticket: a retry of the same response must not raise a second */
  select * into t from public.support_tickets where response_id = p_response;
  if found then return jsonb_build_object('ok', true, 'id', t.id, 'ref', t.ref, 'already', true); end if;
  insert into public.support_tickets (title, body, contact_id, priority, category, opened_via, response_id, waiting_since)
       values (left(trim(p_title), 200), nullif(trim(coalesce(p_body, '')), ''), p_contact,
               coalesce(nullif(p_priority, ''), 'normal'), nullif(trim(coalesce(p_category, '')), ''),
               'form', p_response, now())
  returning * into t;
  /* the event carries no body: the answers are shown at the head of the ticket, and a timeline
     that repeats them under a nameless bubble is the same thing said twice */
  insert into public.support_ticket_events (ticket_id, kind, data)
       values (t.id, 'opened', jsonb_build_object('response', p_response));
  return jsonb_build_object('ok', true, 'id', t.id, 'ref', t.ref);
end;
$$;
REVOKE ALL ON FUNCTION "public"."support_ticket_from_form"("text", "uuid", "uuid", "text", "text", "text") FROM PUBLIC;
REVOKE ALL ON FUNCTION "public"."support_ticket_from_form"("text", "uuid", "uuid", "text", "text", "text") FROM "anon", "authenticated";
GRANT EXECUTE ON FUNCTION "public"."support_ticket_from_form"("text", "uuid", "uuid", "text", "text", "text") TO "service_role";

-- WHAT A TICKET WAS RAISED WITH, for the desk: the answers of the form that raised it, each with
-- the field it answered, so the desk can show them and filter by any of them without knowing in
-- advance what a site asks. The staff only; a ticket with no form answers nothing.
CREATE OR REPLACE FUNCTION "public"."ticket_answers"("p_ticket" "uuid") RETURNS "jsonb"
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
  select case when not public.is_support() then '[]'::jsonb else coalesce((
    select jsonb_agg(jsonb_build_object('field', a.field, 'value', a.value, 'slide', a.slide) order by a.slide, a.field)
      from public.support_tickets t
      join public.form_answers a on a.response_id = t.response_id
     where t.id = p_ticket), '[]'::jsonb) end;
$$;
REVOKE ALL ON FUNCTION "public"."ticket_answers"("uuid") FROM PUBLIC;
REVOKE ALL ON FUNCTION "public"."ticket_answers"("uuid") FROM "anon", "authenticated";
GRANT EXECUTE ON FUNCTION "public"."ticket_answers"("uuid") TO "authenticated", "service_role";

-- EVERY ANSWER ACROSS THE OPEN TICKETS, for the desk's filters: a field, a value, and how many
-- tickets carry it. This is what makes "show me the urgent ones" or "show me the billing ones"
-- work for a question the kit has never heard of — the desk offers whatever the site asked.
CREATE OR REPLACE FUNCTION "public"."ticket_answer_values"("p_open" boolean DEFAULT true) RETURNS "jsonb"
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
  select case when not public.is_support() then '[]'::jsonb else coalesce((
    select jsonb_agg(jsonb_build_object('field', f, 'value', v, 'tickets', n) order by f, n desc, v)
      from (select a.field as f, a.value #>> '{}' as v, count(distinct t.id)::int as n
              from public.support_tickets t
              join public.form_answers a on a.response_id = t.response_id
             where t.response_id is not null
               and (not p_open or t.status not in ('resolved', 'closed'))
               and length(a.value #>> '{}') <= 60   -- a paragraph is not something anybody filters by
             group by 1, 2) x), '[]'::jsonb) end;
$$;
REVOKE ALL ON FUNCTION "public"."ticket_answer_values"(boolean) FROM PUBLIC;
REVOKE ALL ON FUNCTION "public"."ticket_answer_values"(boolean) FROM "anon", "authenticated";
GRANT EXECUTE ON FUNCTION "public"."ticket_answer_values"(boolean) TO "authenticated", "service_role";
