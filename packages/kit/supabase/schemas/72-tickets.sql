-- ---------------------------------------------------------------------------------------------
-- TICKETS. A chat and a ticket are not the same thing and neither contains the other.
--
-- A chat is a conversation: it starts when somebody writes in, it wanders, and it goes quiet. A
-- ticket is a piece of WORK: it has a state, somebody owns it, and it is not finished until it is
-- finished. The two come apart constantly, which is why every serious desk keeps both —
--
--   a ticket outlives its chat: the parcel is lost, the thread goes quiet for three weeks, the
--     carrier finally answers, and the work was open the whole time;
--   a chat covers several tickets: somebody asks about a refund and, while they are there, about
--     a missing chapter — one conversation, two pieces of work;
--   a ticket has no chat at all: the staff notice something themselves and write it down.
--
-- So a ticket is its own row with its own timeline, and the link to a conversation is many to many
-- and optional on both sides. A ticket may have no contact either: "reprint the Kybalion covers"
-- is work nobody reported.
--
-- The timeline is ONE table rather than a comments table beside an audit table, because what a
-- ticket shows is one column of things that happened: somebody wrote, somebody assigned it,
-- somebody changed its state. Splitting them makes the surface stitch two lists back together in
-- the right order, which is the sort of thing that is always slightly wrong.

CREATE TABLE IF NOT EXISTS "public"."support_tickets" (
    "id" "uuid" DEFAULT "gen_random_uuid"() NOT NULL,
    -- the number people say out loud. A sequence, because "ticket 1042" has to mean one ticket
    -- for ever, and a uuid is not something anybody reads over a telephone.
    "ref" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "title" "text" NOT NULL,
    "body" "text",
    -- whose it is. Null is a ticket the staff raised about the business rather than about a person.
    "contact_id" "uuid",
    "status" "text" DEFAULT 'open'::"text" NOT NULL,
    "priority" "text" DEFAULT 'normal'::"text" NOT NULL,
    -- what kind of work it is, from the list the site declares in its policy; free of meaning here
    "category" "text",
    -- who raised it and how it reached us
    "opened_by" "uuid",
    "opened_via" "text" DEFAULT 'desk'::"text" NOT NULL,
    -- THE ANSWERS IT WAS RAISED WITH, where a form raised it. A desk that has to ask "what version,
    -- what did you try, how urgent is it" in the first three replies is a desk doing work a form
    -- could have done — so a form may BE the way a ticket is raised, and its response is the
    -- ticket's. The answers stay where every other form answer lives, read through the response,
    -- which is what lets the desk filter by any field without this table knowing what a field is.
    "response_id" "uuid",
    "due_at" timestamp with time zone,
    "first_reply_at" timestamp with time zone,
    "resolved_at" timestamp with time zone,
    "closed_at" timestamp with time zone,
    -- the moment anything happened on it, which is what the list is ordered by
    "last_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    -- the moment the CONTACT last said something that nobody has answered; null once answered.
    -- The same idea the chat inbox uses, so one set of words says what is owed across the desk.
    "waiting_since" timestamp with time zone,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    -- A TICKET IS OPEN OR IT IS RESOLVED. It had five states and three of them — doing, waiting,
    -- closed — were a guess about how one business works: "In hand" and "With them" assume a queue
    -- with a handover in it, and a ticket here may be a SaaS bug or a coaching question as easily
    -- as a lost parcel. What "With them" was reaching for is waiting_since below, which is a FACT
    -- the rows carry rather than a state anybody has to remember to set.
    -- The old words are still ACCEPTED, so no row written before this becomes unwritable and no
    -- deploy has to rewrite a table to apply the change; lib/desk/shape.js says what each of them
    -- means now, and every surface reads through it. Nothing new is ever written with one.
    CONSTRAINT "support_tickets_status_check" CHECK (("status" = ANY (ARRAY['open'::"text", 'resolved'::"text", 'doing'::"text", 'waiting'::"text", 'closed'::"text"]))),
    CONSTRAINT "support_tickets_priority_check" CHECK (("priority" = ANY (ARRAY['low'::"text", 'normal'::"text", 'high'::"text", 'urgent'::"text"]))),
    CONSTRAINT "support_tickets_via_check" CHECK (("opened_via" = ANY (ARRAY['widget'::"text", 'desk'::"text", 'email'::"text", 'api'::"text", 'chat'::"text", 'form'::"text"]))),
    CONSTRAINT "support_tickets_title_check" CHECK ((("char_length"("title") >= 1) AND ("char_length"("title") <= 200)))
);

