-- the desk's list: every ticket, with who it is about, who is on it, and what is owed
CREATE OR REPLACE FUNCTION "public"."support_tickets_list"("p_status" "text" DEFAULT NULL::"text", "p_assignee" "uuid" DEFAULT NULL::"uuid", "p_q" "text" DEFAULT NULL::"text", "p_limit" integer DEFAULT 100) RETURNS "jsonb"
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
  select case when not public.is_support() then null else coalesce((
    select jsonb_agg(x order by
      case x->>'priority' when 'urgent' then 0 when 'high' then 1 when 'normal' then 2 else 3 end,
      (x->>'last_at') desc)
    from (
      select jsonb_build_object(
        'id', t.id, 'ref', t.ref, 'title', t.title, 'body', t.body,
        'status', t.status, 'priority', t.priority, 'category', t.category,
        'created_at', t.created_at, 'last_at', t.last_at, 'due_at', t.due_at,
        'waiting_since', t.waiting_since, 'resolved_at', t.resolved_at, 'opened_via', t.opened_via,
        'contact', case when t.contact_id is null then null else (
          select jsonb_build_object('id', c.id, 'name', coalesce(nullif(p.display_name, ''), split_part(coalesce(p.email, ''), '@', 1)),
                                    'email', p.email, 'user_id', c.user_id)
            from public.support_contacts c left join public.profiles p on p.id = c.user_id
           where c.id = t.contact_id) end,
        'assignees', coalesce((select jsonb_agg(jsonb_build_object('id', a.user_id,
              'name', coalesce(nullif(p2.display_name, ''), split_part(coalesce(p2.email, ''), '@', 1))))
            from public.support_ticket_assignees a join public.profiles p2 on p2.id = a.user_id
           where a.ticket_id = t.id), '[]'::jsonb),
        /* WHAT IT WAS RAISED WITH, on every row — so the desk can filter by a field it has never
           heard of without opening each ticket to find out. A long answer is left out: a paragraph
           is not a thing anybody filters by, and it would make the list heavy for nothing. */
        'answers', coalesce((select jsonb_object_agg(fa.field, fa.value)
            from public.form_answers fa where fa.response_id = t.response_id and length(fa.value #>> '{}') <= 60), '{}'::jsonb),
        'replies', (select count(*) from public.support_ticket_events e where e.ticket_id = t.id and e.kind in ('reply', 'file')),
        'chats', (select count(*) from public.support_ticket_links l where l.ticket_id = t.id)
      ) as x
      from public.support_tickets t
     where (p_status is null
            or (p_status = 'open' and t.status not in ('resolved', 'closed'))
            or t.status = p_status)
       and (p_assignee is null or exists (select 1 from public.support_ticket_assignees a where a.ticket_id = t.id and a.user_id = p_assignee))
       and (p_q is null or trim(p_q) = '' or t.title ilike '%' || trim(p_q) || '%' or t.body ilike '%' || trim(p_q) || '%'
            or t.ref::text = regexp_replace(trim(p_q), '^#', ''))
     order by t.last_at desc
     limit greatest(coalesce(p_limit, 100), 1)) q), '[]'::jsonb) end;
$$;

-- one ticket, whole: itself, who is on it, its timeline, and the conversations it touches
CREATE OR REPLACE FUNCTION "public"."support_ticket"("p_ticket" "uuid") RETURNS "jsonb"
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
  select case when not public.is_support() then null else jsonb_build_object(
    'ticket', jsonb_build_object(
      'id', t.id, 'ref', t.ref, 'title', t.title, 'body', t.body, 'status', t.status,
      'priority', t.priority, 'category', t.category, 'created_at', t.created_at,
      'last_at', t.last_at, 'due_at', t.due_at, 'waiting_since', t.waiting_since,
      'resolved_at', t.resolved_at, 'closed_at', t.closed_at, 'opened_via', t.opened_via,
      'contact', case when t.contact_id is null then null else (
        select jsonb_build_object('id', c.id, 'name', coalesce(nullif(p.display_name, ''), split_part(coalesce(p.email, ''), '@', 1)),
                                  'email', p.email, 'user_id', c.user_id, 'notes', c.notes)
          from public.support_contacts c left join public.profiles p on p.id = c.user_id
         where c.id = t.contact_id) end),
    /* what it was raised with, where a form raised it: the answers, in the order they were asked.
       The desk shows them at the head of the ticket so nobody has to ask for them again. */
    'answers', coalesce((select jsonb_agg(jsonb_build_object('field', fa.field, 'value', fa.value) order by fa.slide, fa.field)
        from public.form_answers fa where fa.response_id = t.response_id), '[]'::jsonb),
    'assignees', coalesce((select jsonb_agg(jsonb_build_object('id', a.user_id,
          'name', coalesce(nullif(p2.display_name, ''), split_part(coalesce(p2.email, ''), '@', 1))))
        from public.support_ticket_assignees a join public.profiles p2 on p2.id = a.user_id
       where a.ticket_id = t.id), '[]'::jsonb),
    'timeline', coalesce((select jsonb_agg(jsonb_build_object(
          'id', e.id, 'kind', e.kind, 'body', e.body, 'internal', e.internal, 'data', e.data,
          'by_contact', e.by_contact, 'agent', e.agent_id,
          'agent_name', (select coalesce(nullif(p3.display_name, ''), split_part(coalesce(p3.email, ''), '@', 1)) from public.profiles p3 where p3.id = e.agent_id),
          'name', e.attachment_name, 'type', e.attachment_type, 'size', e.attachment_size, 'path', e.attachment_path,
          'created_at', e.created_at) order by e.created_at)
        from public.support_ticket_events e where e.ticket_id = t.id), '[]'::jsonb),
    'chats', coalesce((select jsonb_agg(jsonb_build_object('id', l.conversation_id,
          'status', cv.status, 'last_at', cv.last_message_at))
        from public.support_ticket_links l join public.support_conversations cv on cv.id = l.conversation_id
       where l.ticket_id = t.id), '[]'::jsonb)) end
    from public.support_tickets t where t.id = p_ticket;
$$;

-- A PERSON'S OWN TICKETS, for the widget and for their own column in the spaces surface. Never
-- the internal notes, never anybody else's ticket, and no count of what the desk is doing.
CREATE OR REPLACE FUNCTION "public"."support_tickets_mine"() RETURNS "jsonb"
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
  select coalesce(jsonb_agg(jsonb_build_object(
      'id', t.id, 'ref', t.ref, 'title', t.title, 'status', t.status,
      'created_at', t.created_at, 'last_at', t.last_at, 'resolved_at', t.resolved_at,
      'replies', (select count(*) from public.support_ticket_events e
                   where e.ticket_id = t.id and e.kind in ('reply', 'file') and not e.internal)
    ) order by t.last_at desc), '[]'::jsonb)
    from public.support_tickets t
    join public.support_contacts c on c.id = t.contact_id
   where auth.uid() is not null and c.user_id = auth.uid();
$$;

-- one of their own, with the timeline they are allowed to read
CREATE OR REPLACE FUNCTION "public"."support_ticket_mine"("p_ticket" "uuid") RETURNS "jsonb"
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
  select case when not exists (
      select 1 from public.support_tickets t join public.support_contacts c on c.id = t.contact_id
       where t.id = p_ticket and auth.uid() is not null and c.user_id = auth.uid())
    then null else jsonb_build_object(
      'ticket', (select jsonb_build_object('id', t.id, 'ref', t.ref, 'title', t.title, 'body', t.body,
          'status', t.status, 'created_at', t.created_at, 'last_at', t.last_at, 'resolved_at', t.resolved_at)
        from public.support_tickets t where t.id = p_ticket),
      'timeline', coalesce((select jsonb_agg(jsonb_build_object(
            'id', e.id, 'kind', e.kind, 'body', e.body, 'by_contact', e.by_contact, 'data', e.data,
            'agent_name', (select coalesce(nullif(p.display_name, ''), split_part(coalesce(p.email, ''), '@', 1)) from public.profiles p where p.id = e.agent_id),
            'name', e.attachment_name, 'type', e.attachment_type, 'created_at', e.created_at) order by e.created_at)
          from public.support_ticket_events e
         where e.ticket_id = p_ticket and not e.internal and e.kind in ('opened', 'reply', 'file', 'status')), '[]'::jsonb)) end;
$$;

-- ---------------------------------------------------------------------------------------------
-- THE WRITES. Raising, moving and answering a ticket go through functions rather than policies,
-- because each of them is several rows that must agree: a status change is both a column and a
-- line on the timeline, and a surface that writes one without the other leaves a ticket whose
-- history does not explain its state.

CREATE OR REPLACE FUNCTION "public"."support_ticket_open"("p_title" "text", "p_body" "text" DEFAULT NULL::"text", "p_contact" "uuid" DEFAULT NULL::"uuid", "p_priority" "text" DEFAULT 'normal'::"text", "p_category" "text" DEFAULT NULL::"text", "p_conversation" "uuid" DEFAULT NULL::"uuid", "p_assign" "uuid"[] DEFAULT NULL::"uuid"[]) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
declare t public.support_tickets; a uuid;
begin
  -- Staff, or the ONE other thing that may raise a ticket: a bot, through agent_raise_ticket,
  -- which is the service role's alone and derives the contact from the run rather than being told
  -- it. It says so for its own transaction, as space_poll_close does. Without this every ticket a
  -- bot raised was refused with 'not-staff' — auth.uid() is null under the service key, so is_staff()
  -- is false — and "hand it to a person" quietly did nothing at all.
  if not (public.is_support() or coalesce(current_setting('app.bot_ticket', true), '') = '1') then
    return jsonb_build_object('error', 'not-staff');
  end if;
  if coalesce(trim(p_title), '') = '' then return jsonb_build_object('error', 'title'); end if;
  insert into public.support_tickets (title, body, contact_id, priority, category, opened_by, opened_via)
       values (trim(p_title), nullif(trim(coalesce(p_body, '')), ''), p_contact,
               coalesce(p_priority, 'normal'), nullif(trim(coalesce(p_category, '')), ''), auth.uid(),
               case when p_conversation is not null then 'chat' else 'desk' end)
  returning * into t;
  insert into public.support_ticket_events (ticket_id, kind, agent_id, body)
       values (t.id, 'opened', auth.uid(), nullif(trim(coalesce(p_body, '')), ''));
  if p_conversation is not null then
    insert into public.support_ticket_links (ticket_id, conversation_id, linked_by)
         values (t.id, p_conversation, auth.uid()) on conflict do nothing;
    insert into public.support_ticket_events (ticket_id, kind, agent_id, data)
         values (t.id, 'linked', auth.uid(), jsonb_build_object('conversation', p_conversation));
  end if;
  foreach a in array coalesce(p_assign, '{}'::uuid[]) loop
    insert into public.support_ticket_assignees (ticket_id, user_id, added_by) values (t.id, a, auth.uid()) on conflict do nothing;
    insert into public.support_ticket_events (ticket_id, kind, agent_id, data) values (t.id, 'assigned', auth.uid(), jsonb_build_object('who', a));
  end loop;
  return jsonb_build_object('ok', true, 'id', t.id, 'ref', t.ref);
end;
$$;

CREATE OR REPLACE FUNCTION "public"."support_ticket_set"("p_ticket" "uuid", "p_status" "text" DEFAULT NULL::"text", "p_priority" "text" DEFAULT NULL::"text", "p_title" "text" DEFAULT NULL::"text", "p_category" "text" DEFAULT NULL::"text", "p_due" timestamp with time zone DEFAULT NULL::timestamp with time zone, "p_clear_due" boolean DEFAULT false) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
declare t public.support_tickets;
begin
  if not public.is_support() then return jsonb_build_object('error', 'not-staff'); end if;
  select * into t from public.support_tickets where id = p_ticket;
  if not found then return jsonb_build_object('error', 'gone'); end if;
  if p_status is not null and p_status is distinct from t.status then
    update public.support_tickets
       set status = p_status,
           resolved_at = case when p_status = 'resolved' then now() when p_status in ('open', 'doing', 'waiting') then null else resolved_at end,
           closed_at = case when p_status = 'closed' then now() when p_status <> 'closed' then null else closed_at end,
           updated_at = now()
     where id = p_ticket;
    insert into public.support_ticket_events (ticket_id, kind, agent_id, data)
         values (p_ticket, 'status', auth.uid(), jsonb_build_object('from', t.status, 'to', p_status));
  end if;
  if p_priority is not null and p_priority is distinct from t.priority then
    update public.support_tickets set priority = p_priority, updated_at = now() where id = p_ticket;
    insert into public.support_ticket_events (ticket_id, kind, agent_id, data)
         values (p_ticket, 'priority', auth.uid(), jsonb_build_object('from', t.priority, 'to', p_priority));
  end if;
  if p_title is not null and trim(p_title) <> '' then
    update public.support_tickets set title = trim(p_title), updated_at = now() where id = p_ticket;
  end if;
  if p_category is not null then
    update public.support_tickets set category = nullif(trim(p_category), ''), updated_at = now() where id = p_ticket;
  end if;
  if p_clear_due then
    update public.support_tickets set due_at = null, updated_at = now() where id = p_ticket;
    insert into public.support_ticket_events (ticket_id, kind, agent_id, data) values (p_ticket, 'due', auth.uid(), '{}'::jsonb);
  elsif p_due is not null then
    update public.support_tickets set due_at = p_due, updated_at = now() where id = p_ticket;
    insert into public.support_ticket_events (ticket_id, kind, agent_id, data)
         values (p_ticket, 'due', auth.uid(), jsonb_build_object('at', p_due));
  end if;
  return jsonb_build_object('ok', true);
end;
$$;

CREATE OR REPLACE FUNCTION "public"."support_ticket_assign"("p_ticket" "uuid", "p_user" "uuid", "p_on" boolean DEFAULT true) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
begin
  if not public.is_support() then return jsonb_build_object('error', 'not-staff'); end if;
  if p_on then
    insert into public.support_ticket_assignees (ticket_id, user_id, added_by) values (p_ticket, p_user, auth.uid())
    on conflict do nothing;
    insert into public.support_ticket_events (ticket_id, kind, agent_id, data)
         values (p_ticket, 'assigned', auth.uid(), jsonb_build_object('who', p_user));
  else
    delete from public.support_ticket_assignees where ticket_id = p_ticket and user_id = p_user;
    insert into public.support_ticket_events (ticket_id, kind, agent_id, data)
         values (p_ticket, 'unassigned', auth.uid(), jsonb_build_object('who', p_user));
  end if;
  return jsonb_build_object('ok', true);
end;
$$;

-- a reply the contact will see, or a note only the desk will
CREATE OR REPLACE FUNCTION "public"."support_ticket_say"("p_ticket" "uuid", "p_body" "text", "p_internal" boolean DEFAULT false) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
begin
  if not public.is_support() then return jsonb_build_object('error', 'not-staff'); end if;
  if coalesce(trim(p_body), '') = '' then return jsonb_build_object('error', 'empty'); end if;
  insert into public.support_ticket_events (ticket_id, kind, agent_id, body, internal)
       values (p_ticket, case when p_internal then 'note' else 'reply' end, auth.uid(), trim(p_body), p_internal);
  return jsonb_build_object('ok', true);
end;
$$;

-- tie a ticket to a conversation, or untie it. Many to many, so neither is the other's parent.
