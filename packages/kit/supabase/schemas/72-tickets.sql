-- ---------------------------------------------------------------------------------------------
-- WHAT MOVES A TICKET. One trigger keeps the three derived moments true, so no surface has to
-- remember to: when anything happens the ticket has moved; when the contact writes and nobody has
-- answered, it is waiting on us; when an agent replies, it is not, and if that was the first
-- answer the clock on it stops for good.

CREATE OR REPLACE FUNCTION "public"."support_ticket_bump"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
begin
  update public.support_tickets t
     set last_at = new.created_at,
         updated_at = now(),
         waiting_since = case
           when new.kind in ('reply', 'file') and new.by_contact then coalesce(t.waiting_since, new.created_at)
           when new.kind in ('reply', 'file') and not new.by_contact then null
           else t.waiting_since end,
         first_reply_at = case
           when new.kind = 'reply' and not new.by_contact and not new.internal then coalesce(t.first_reply_at, new.created_at)
           else t.first_reply_at end,
         -- a contact writing on something finished with opens it again, exactly as a chat does
         status = case when new.by_contact and t.status in ('resolved', 'closed') then 'open' else t.status end,
         resolved_at = case when new.by_contact and t.status in ('resolved', 'closed') then null else t.resolved_at end
   where t.id = new.ticket_id;
  return null;
end;
$$;

CREATE OR REPLACE TRIGGER "trg_support_ticket_bump" AFTER INSERT ON "public"."support_ticket_events"
  FOR EACH ROW EXECUTE FUNCTION "public"."support_ticket_bump"();

