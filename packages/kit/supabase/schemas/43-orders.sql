    "sku" "text" NOT NULL,
    "key" "text",
    "variant" "text" DEFAULT ''::"text" NOT NULL,
    "title" "text",
    "variant_title" "text",
    "options" "jsonb",
    "unit_price" integer NOT NULL,
    "quantity" integer DEFAULT 1 NOT NULL,
    -- WHAT THE KIND DERIVED for this variant, opaque to everything here: the store stores the
    -- record and hands it to a supplier, and never opens it.
