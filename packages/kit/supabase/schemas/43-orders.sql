-- ═══════════════════ WHAT IS DERIVED, AND NEVER STORED ═══════════════════
--
-- There is no `payment_status` column and no `fulfilment_status` column. Both are totals of rows
-- this schema already holds, and a stored total is a second source that disagrees with the rows
-- the first time anything goes wrong — see 41-inventory.sql, which says the same about `available`
-- for the same reason. Medusa stores eight such numbers on its order item and then owns keeping
-- all eight true.

-- THE LINES AT A VERSION: for each line, the newest row at or before N. An edit copies forward
-- only what it touched, so a line nobody edited is read from the version it was written at.
CREATE OR REPLACE FUNCTION "public"."order_lines"("p_order" "uuid", "p_version" integer DEFAULT NULL)
RETURNS SETOF "public"."order_items"
LANGUAGE "sql" STABLE SECURITY DEFINER SET "search_path" TO 'public'
AS $$
  select distinct on (i.line) i.*
    from public.order_items i
   where i.order_id = p_order
     and i.version <= coalesce(p_version, (select o.version from public.orders o where o.id = p_order))
   order by i.line, i.version desc
$$;

-- WHAT THE ORDER COSTS at a version: its live lines, plus the shipping.
CREATE OR REPLACE FUNCTION "public"."order_total"("p_order" "uuid", "p_version" integer DEFAULT NULL)
RETURNS integer
LANGUAGE "sql" STABLE SECURITY DEFINER SET "search_path" TO 'public'
AS $$
  select coalesce((select sum(l.unit_price * l.quantity)::int
                     from public.order_lines(p_order, p_version) l
                    where not l.removed), 0)
       + coalesce((select o.shipping_total from public.orders o where o.id = p_order), 0)
$$;

-- PAID, PART-PAID, REFUNDED OR OWING — from the transactions, every time it is asked.
CREATE OR REPLACE FUNCTION "public"."order_payment"("p_order" "uuid")
RETURNS "text"
LANGUAGE "sql" STABLE SECURITY DEFINER SET "search_path" TO 'public'
AS $$
  select case
    -- NOTHING TAKEN AND NOTHING GIVEN BACK is unpaid; nothing taken BECAUSE it was all given
    -- back is refunded. The sum is 0 either way, which is why the sum alone cannot say.
    when t.given = 0 and coalesce(t.taken, 0) = 0 then 'unpaid'
    when coalesce(t.taken, 0) <= 0 and t.given > 0 then 'refunded'
    when t.taken >= public.order_total(p_order) then (case when t.given > 0 then 'part_refunded' else 'paid' end)
    else 'part_paid'
  end
    from (select coalesce(sum(amount), 0)::int as taken,
                 coalesce(sum(case when amount < 0 then -amount else 0 end), 0)::int as given
            from public.order_transactions where order_id = p_order) t
$$;

-- AND HOW MUCH OF IT HAS GONE OUT, by line: the quantities on its fulfilments against the
-- quantities on its lines. Nothing, some, or all.
CREATE OR REPLACE FUNCTION "public"."order_fulfilment"("p_order" "uuid")
RETURNS "text"
LANGUAGE "sql" STABLE SECURITY DEFINER SET "search_path" TO 'public'
AS $$
  select case
    when w.want = 0 then 'nothing_to_send'
    when w.sent = 0 then 'unfulfilled'
    when w.sent >= w.want then 'fulfilled'
    else 'part_fulfilled'
  end
    from (select coalesce((select sum(l.quantity)::int from public.order_lines(p_order) l where not l.removed), 0) as want,
                 coalesce((select sum(fi.quantity)::int
                             from public.fulfilment_items fi
                             join public.fulfilments f on f.id = fi.fulfilment_id
                            where f.order_id = p_order
                              and f.status not in ('rejected', 'canceled', 'failed')), 0) as sent) w
$$;

-- ─────────────── the transactions sum to the total, or the write is refused ───────────────
--
-- Refused AT THE WRITE, not checked afterwards by something that runs later: a row that should
-- never have existed is a row somebody has to find. Taking more than the order costs is the
-- mistake worth catching — a double capture, a webhook replayed against the wrong order — and
-- giving back more than was taken is the other direction of the same error.
CREATE OR REPLACE FUNCTION "public"."order_transaction_guard"() RETURNS "trigger"
LANGUAGE "plpgsql" SECURITY DEFINER SET "search_path" TO 'public'
AS $$
DECLARE
  taken int;
  owed  int;
BEGIN
  select coalesce(sum(amount), 0)::int into taken from public.order_transactions where order_id = NEW.order_id;
  owed := public.order_total(NEW.order_id);
  if taken > owed then
    raise exception 'order %: the transactions come to % and the order costs % — more cannot be taken than is owed', NEW.order_id, taken, owed
      using errcode = 'check_violation';
  end if;
  if taken < 0 then
    raise exception 'order %: the transactions come to %, which is less than nothing — more cannot be given back than was taken', NEW.order_id, taken
      using errcode = 'check_violation';
  end if;
  return NEW;
END;
$$;
DROP TRIGGER IF EXISTS "order_transactions_sum" ON "public"."order_transactions";
CREATE CONSTRAINT TRIGGER "order_transactions_sum"
  AFTER INSERT OR UPDATE ON "public"."order_transactions"
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION "public"."order_transaction_guard"();

-- ─────────────── an edit raises the version and copies forward what it touches ───────────────
CREATE OR REPLACE FUNCTION "public"."order_edit"("p_order" "uuid", "p_lines" "jsonb")
RETURNS integer
LANGUAGE "plpgsql" SECURITY DEFINER SET "search_path" TO 'public'
AS $$
DECLARE
  v   int;
  row jsonb;
  was public.order_items%ROWTYPE;
BEGIN
  -- an administrator through the API, or the service role from a function: both are the shop
  if not public.is_admin() and auth.role() <> 'service_role' then raise exception 'not allowed'; end if;
  update public.orders set version = version + 1, updated_at = now() where id = p_order returning version into v;
  if v is null then raise exception 'no such order'; end if;
  for row in select * from jsonb_array_elements(p_lines) loop
    select * into was from public.order_lines(p_order, v - 1) where line = (row->>'line')::uuid;
    if was.id is null then raise exception 'order %: no line %', p_order, row->>'line'; end if;
    insert into public.order_items (order_id, line, version, sku, key, variant, title, variant_title, options, unit_price, quantity, artefacts, removed)
    values (p_order, was.line, v, was.sku, was.key, was.variant, was.title, was.variant_title, was.options,
            coalesce((row->>'unit_price')::int, was.unit_price),
            coalesce((row->>'quantity')::int, was.quantity),
            was.artefacts,
            coalesce((row->>'removed')::boolean, was.removed));
  end loop;
  return v;
END;
$$;

-- ─────────────── stock comes back on RECEIVED, and never on requested ───────────────
--
-- The rule this exists for. A return is a conversation until the thing is in the shop's hands;
-- crediting the shelf at the request sells a unit that has not come back, and the shop finds out
-- when the next buyer's order cannot be filled.
CREATE OR REPLACE FUNCTION "public"."return_received"() RETURNS "trigger"
LANGUAGE "plpgsql" SECURITY DEFINER SET "search_path" TO 'public'
AS $$
DECLARE
  it record;
  ln record;
BEGIN
  if NEW.status = 'received' and (OLD.status is distinct from 'received') then
    for it in select * from public.return_items where return_id = NEW.id and restock loop
      select * into ln from public.order_lines(NEW.order_id, NEW.order_version) where line = it.line;
      if ln.sku is not null then
        perform public.inventory_give(ln.sku, ln.variant, it.quantity, 'returned', NEW.id::text);
      end if;
    end loop;
    NEW.received_at := coalesce(NEW.received_at, now());
  end if;
  return NEW;
END;
$$;
DROP TRIGGER IF EXISTS "returns_restock" ON "public"."returns";
CREATE TRIGGER "returns_restock" BEFORE UPDATE ON "public"."returns"
  FOR EACH ROW EXECUTE FUNCTION "public"."return_received"();

-- ───────────────────────────── who may read what ─────────────────────────────
--
-- A buyer reads their own order and nothing else; an administrator reads every one. NOTHING here
-- is written from a client: an order is written by the ledger from what the payment processor
-- says was paid, a fulfilment by the supplier seam, a return by the admin's own action. A policy
-- that let a browser insert a transaction would let it say it had paid.

ALTER TABLE "public"."orders" ENABLE ROW LEVEL SECURITY;
CREATE POLICY "orders_select_own" ON "public"."orders" FOR SELECT TO "authenticated" USING ((("user_id" = "auth"."uid"()) OR "public"."is_admin"()));

ALTER TABLE "public"."order_items" ENABLE ROW LEVEL SECURITY;
CREATE POLICY "order_items_select_own" ON "public"."order_items" FOR SELECT TO "authenticated" USING ((EXISTS (SELECT 1 FROM "public"."orders" "o" WHERE (("o"."id" = "order_items"."order_id") AND (("o"."user_id" = "auth"."uid"()) OR "public"."is_admin"())))));

ALTER TABLE "public"."order_transactions" ENABLE ROW LEVEL SECURITY;
CREATE POLICY "order_transactions_select_own" ON "public"."order_transactions" FOR SELECT TO "authenticated" USING ((EXISTS (SELECT 1 FROM "public"."orders" "o" WHERE (("o"."id" = "order_transactions"."order_id") AND (("o"."user_id" = "auth"."uid"()) OR "public"."is_admin"())))));

ALTER TABLE "public"."fulfilments" ENABLE ROW LEVEL SECURITY;
CREATE POLICY "fulfilments_select_own" ON "public"."fulfilments" FOR SELECT TO "authenticated" USING ((("user_id" = "auth"."uid"()) OR "public"."is_admin"()));
-- an administrator moves one by hand: sending it again, marking the shop's own post room sent
