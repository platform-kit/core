-- AN ORDER HAS A LIFE, AND THE LIFE IS ROWS RATHER THAN A COLUMN THAT KEEPS BEING OVERWRITTEN.
--
-- A purchase said what was bought and nothing else: no address to change, no way to send half of
-- it today and half next week, no way to take one thing back, and no record of what the order
-- looked like before somebody edited it. Every shop needs all four, and a shop that grows them
-- one column at a time ends with `fulfilment_status` and `payment_status` sitting next to the
-- rows they are supposed to summarise, disagreeing with them.
--
-- FOUR TABLES AND NO FIFTH STATE COLUMN:
--
--   orders               what a buyer placed, and its VERSION
--   order_items          the lines, each at a version — an edit raises the order's version and
--                        copies forward only what it touched
--   order_transactions   money in and out, which must sum to what the order says it costs
--   fulfilments          a parcel, a file, a booking — what a supplier was asked to make or send
--                        (+ fulfilment_items: which lines, and how many of each)
--   returns              what came back (+ return_items), with states of their own
--
-- WHAT IS NOT HERE IS THE POINT. There is no `payment_status` and no `fulfilment_status`: both
-- are DERIVED (`order_payment`, `order_fulfilment`) from the transactions and the fulfilments,
-- every time they are asked for. Medusa stores eight quantity columns on its order item —
-- fulfilled, delivered, shipped, return_requested, return_received, return_dismissed,
-- written_off — and then owns the job of keeping all eight true; this project's declaration rule
-- already says what to do with a number that is a total of rows, and it is the same answer stock
-- gave (41-inventory.sql): derive it. A stored total and the rows it totals are two sources that
-- disagree the first time anything goes wrong, and the one that is wrong is the one every page
-- reads.
--
-- VERSIONING, after Medusa's `order_item` (packages/modules/order/src/models/order-item.ts): the
-- order carries a version, every line carries the version it was written at, and a read at
-- version N takes, for each line, the newest row at or before N. Medusa copies every line forward
-- on every change; this copies only what the edit touched, which is a cheaper write and the same
-- answer — an invoice rendered again at version 1 after an edit shows version 1.
--
-- NOTHING HERE NAMES A KIND OF THING. A fulfilment does not know what a book is: it carries the
-- variant's own `chosen` values and whatever the kind derived as `artefacts`, exactly as a
-- supplier is handed them (build/kinds, _shared/suppliers). See the note on the legacy print
-- columns at the foot of this file, which is the one thing that is not yet true and says so.

-- ───────────────────────────── the order ─────────────────────────────

CREATE TABLE IF NOT EXISTS "public"."orders" (
    "id" "uuid" DEFAULT "gen_random_uuid"() NOT NULL,
    -- what a person calls it: a number that counts up, so nobody reads a uuid aloud
    "number" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- THE VERSION the order is AT. Reading the order with no version means this one.
    "version" integer DEFAULT 1 NOT NULL,
    "user_id" "uuid",
    -- a guest checks out with no account, so the address is the only thing that reaches them
    "email" "text",
    "currency" "text" DEFAULT 'usd'::"text" NOT NULL,
    -- the session this came from: one order per paid session, which is what makes a replayed
    -- webhook harmless
    "checkout_session" "text",
    "status" "text" DEFAULT 'open'::"text" NOT NULL,
    "shipping_address" "jsonb",
    "billing_address" "jsonb",
    -- our own shipping word (standard · priority · express), not a carrier's
    "shipping_level" "text" DEFAULT 'standard'::"text" NOT NULL,
    -- what the buyer paid for shipping, in cents, kept apart from the lines
    "shipping_total" integer DEFAULT 0 NOT NULL,
    "metadata" "jsonb",
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    CONSTRAINT "orders_status_check" CHECK (("status" = ANY (ARRAY['open'::"text", 'completed'::"text", 'canceled'::"text", 'archived'::"text"])))
);
