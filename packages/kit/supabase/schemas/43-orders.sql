-- ─────────────── a line of an order, written once however often the event arrives ───────────────
--
-- The same arrangement `purchase_write` is in and for the same reason: a line is identified by the
-- order AND the sku AND the shape, which is a partial index over the live version, and neither
-- Postgres nor PostgREST can infer a conflict target from a column list alone. So it is a function.
--
-- A replayed webhook, or the client's confirm racing it, writes the SAME line rather than a second
-- one — and `line` is generated once, so every later version of that line is recognisably it.
CREATE UNIQUE INDEX IF NOT EXISTS "order_items_live_key" ON "public"."order_items" USING "btree" ("order_id", "sku", "variant", "version");

CREATE OR REPLACE FUNCTION "public"."order_line_write"("p" "jsonb")
RETURNS "uuid"
LANGUAGE "plpgsql" SECURITY DEFINER SET "search_path" TO 'public'
AS $$
DECLARE
  v  int;
  id uuid;
BEGIN
  if not public.is_admin() and auth.role() <> 'service_role' then raise exception 'not allowed'; end if;
  select o.version into v from public.orders o where o.id = (p->>'order_id')::uuid;
  if v is null then raise exception 'no such order'; end if;
  insert into public.order_items (order_id, line, version, sku, key, variant, title, variant_title, options, unit_price, quantity)
  values ((p->>'order_id')::uuid, gen_random_uuid(), v, coalesce(p->>'sku', ''), p->>'key', coalesce(p->>'variant', ''),
          p->>'title', p->>'variant_title', p->'options',
          coalesce((p->>'unit_price')::int, 0), coalesce((p->>'quantity')::int, 1))
  on conflict (order_id, sku, variant, version) do update
    set quantity = excluded.quantity, unit_price = excluded.unit_price, title = excluded.title
  returning order_items.line into id;
  return id;
END;
$$;
GRANT ALL ON FUNCTION "public"."order_line_write"("jsonb") TO "authenticated", "service_role";

-- ─────────────── the admin's one read ───────────────
--
-- An order, what was on it, what it cost, what has been paid, what has gone out and what has come
-- back — in ONE answer, as `admin_support` and `admin_find` are. Four round trips per page would
-- be four chances for the list to show an order and its parcels from different moments.
--
-- Purchases written before any of this had no order; they are returned too, flat, so nothing that
-- was visible yesterday is invisible today. A shop with no orders at all still sees its sales.
CREATE OR REPLACE FUNCTION "public"."admin_orders"("p_limit" integer DEFAULT 200)
RETURNS "jsonb"
LANGUAGE "sql" STABLE SECURITY DEFINER SET "search_path" TO 'public'
AS $$
  select case when not public.is_admin() and auth.role() <> 'service_role' then null else
    jsonb_build_object(
      'orders', coalesce((
        select jsonb_agg(x order by x->>'created_at' desc) from (
          select jsonb_build_object(
            'id', o.id, 'number', o.number, 'version', o.version, 'status', o.status,
            'email', o.email, 'user_id', o.user_id, 'currency', o.currency,
            'created_at', o.created_at, 'shipping_total', o.shipping_total,
            'shipping_address', o.shipping_address,
            'checkout_session', o.checkout_session,
            'total', public.order_total(o.id),
            -- derived, every time: never a column to disagree with the rows
            'payment', public.order_payment(o.id),
            'fulfilment', public.order_fulfilment(o.id),
            'lines', coalesce((select jsonb_agg(jsonb_build_object(
                'line', l.line, 'sku', l.sku, 'variant', l.variant, 'title', l.title,
                'variant_title', l.variant_title, 'unit_price', l.unit_price, 'quantity', l.quantity,
                'removed', l.removed))
              from public.order_lines(o.id) l), '[]'::jsonb),
            'transactions', coalesce((select jsonb_agg(jsonb_build_object(
                'amount', t.amount, 'reason', t.reason, 'reference', t.reference, 'created_at', t.created_at)
                order by t.created_at)
              from public.order_transactions t where t.order_id = o.id), '[]'::jsonb),
            'fulfilments', coalesce((select jsonb_agg(jsonb_build_object(
                'id', f.id, 'supplier', f.supplier, 'status', f.status, 'tracking', f.tracking,
                'quantity', f.quantity, 'proof', f.proof, 'error', f.error, 'book', f.book, 'format', f.format)
                order by f.created_at)
              from public.fulfilments f where f.order_id = o.id), '[]'::jsonb),
            'returns', coalesce((select jsonb_agg(jsonb_build_object(
                'id', r.id, 'number', r.number, 'status', r.status, 'reason', r.reason,
                'exchange_order_id', r.exchange_order_id, 'requested_at', r.requested_at)
                order by r.requested_at)
              from public.returns r where r.order_id = o.id), '[]'::jsonb)
          ) as x
          from public.orders o order by o.created_at desc limit p_limit
        ) q), '[]'::jsonb),
      -- and the sales from before there were orders, so the page is never emptier than it was
      'loose', coalesce((
        select jsonb_agg(jsonb_build_object(
            'id', p.id, 'sku', p.sku, 'variant', p.variant, 'title', p.title,
            'amount_total', p.amount_total, 'currency', p.currency, 'status', p.status,
            'email', p.email, 'user_id', p.user_id, 'created_at', p.created_at,
            'quantity', p.quantity, 'session', coalesce(p.checkout_identity, p.stripe_checkout_session_id))
            order by p.created_at desc)
          from public.purchases p
         where coalesce(p.checkout_identity, p.stripe_checkout_session_id) is null
            or not exists (select 1 from public.orders o where o.checkout_session = coalesce(p.checkout_identity, p.stripe_checkout_session_id))), '[]'::jsonb)
    )
  end
$$;
GRANT ALL ON FUNCTION "public"."admin_orders"(integer) TO "authenticated", "service_role";
